// Usage: node scripts/build-kerala-map.mjs
// Projects scripts/kerala-districts.geojson to simplified SVG paths -> src/lib/kerala-geo.ts
import { readFileSync, writeFileSync } from "node:fs";

const geo = JSON.parse(readFileSync(new URL("./kerala-districts.geojson", import.meta.url)));
const SCALE = 200;            // px per degree
const TOL = 0.45;             // Douglas-Peucker tolerance (px)
let minLng = Infinity, maxLat = -Infinity, maxLng = -Infinity, minLat = Infinity;
const rings = (g) => (g.type === "MultiPolygon" ? g.coordinates.flat() : g.coordinates);
for (const f of geo.features) for (const r of rings(f.geometry)) for (const [x, y] of r) {
  minLng = Math.min(minLng, x); maxLng = Math.max(maxLng, x); minLat = Math.min(minLat, y); maxLat = Math.max(maxLat, y);
}
const k = Math.cos(((minLat + maxLat) / 2) * Math.PI / 180);
const proj = ([lng, lat]) => [(lng - minLng) * k * SCALE, (maxLat - lat) * SCALE];

function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts[pts.length - 1]];
  let idx = -1, max = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const [x, y] = pts[i];
    const dx = b[0] - a[0], dy = b[1] - a[1];
    const d = dx === 0 && dy === 0 ? Math.hypot(x - a[0], y - a[1]) : Math.abs(dy * x - dx * y + b[0] * a[1] - b[1] * a[0]) / Math.hypot(dx, dy);
    if (d > max) { max = d; idx = i; }
  }
  if (max > tol) return [...dp(pts.slice(0, idx + 1), tol).slice(0, -1), ...dp(pts.slice(idx), tol)];
  return [a, b];
}
const area = (r) => Math.abs(r.reduce((s, p, i) => { const q = r[(i + 1) % r.length]; return s + p[0] * q[1] - q[0] * p[1]; }, 0) / 2);
const centroid = (r) => {
  let a = 0, cx = 0, cy = 0;
  r.forEach((p, i) => { const q = r[(i + 1) % r.length]; const c = p[0] * q[1] - q[0] * p[1]; a += c; cx += (p[0] + q[0]) * c; cy += (p[1] + q[1]) * c; });
  a /= 2; return [cx / (6 * a), cy / (6 * a)];
};

const out = {};
for (const f of geo.features) {
  const slug = f.properties.district.toLowerCase();
  const rs = rings(f.geometry).map((r) => dp(r.map(proj), TOL)).filter((r) => r.length >= 4 && area(r) > 4); // drop tiny islands
  const big = rs.reduce((m, r) => (area(r) > area(m) ? r : m));
  const d = rs.map((r) => "M" + r.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join("L") + "Z").join("");
  const [cx, cy] = centroid(big);
  out[slug] = { d, cx: +cx.toFixed(1), cy: +cy.toFixed(1) };
}
const W = Math.ceil((maxLng - minLng) * k * SCALE), H = Math.ceil((maxLat - minLat) * SCALE);
writeFileSync(new URL("../src/lib/kerala-geo.ts", import.meta.url),
`// GENERATED by scripts/build-kerala-map.mjs — do not edit by hand.
export const KERALA_VIEWBOX = { width: ${W}, height: ${H} };
export const KERALA_GEO: Record<string, { d: string; cx: number; cy: number }> = ${JSON.stringify(out)};
`);
console.log("viewBox", W, H, "districts", Object.keys(out).length);
